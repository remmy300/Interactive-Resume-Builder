const SKILL_DEFINITIONS: Array<{
  definition: SkillDefinition;
  matchAliases: string[];
}> = SKILL_INPUTS.map((input) => {
  const term = normalizeTerm(input.display);
  const aliases = [
    ...new Set([term, ...(input.aliases ?? []).map(normalizeTerm)]),
  ].filter(Boolean);
  const matchAliases = [
    ...new Set([...aliases, ...(input.related ?? []).map(normalizeTerm)]),
  ].filter(Boolean);
  return {
    definition: { term, display: input.display, aliases },
    matchAliases,
  };
});

export const SKILL_LOOKUP = new Map<string, SkillDefinition>();
export const SKILL_ALIASES = new Map<string, string[]>();

// Canonical names always win. Broad "related term" aliases (for example SQL
// listing PostgreSQL) are only used for resume matching; they must not replace
// the specific skill when a posting says "PostgreSQL".
for (const { definition } of SKILL_DEFINITIONS) {
  SKILL_LOOKUP.set(definition.term, definition);
}
for (const { definition, matchAliases } of SKILL_DEFINITIONS) {
  for (const alias of definition.aliases) {
    if (!SKILL_LOOKUP.has(alias)) SKILL_LOOKUP.set(alias, definition);
  }
  SKILL_ALIASES.set(definition.term, matchAliases);
}

